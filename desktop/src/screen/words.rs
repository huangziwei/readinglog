//! What the window says that no Kindle screen does, in the Kindle's five
//! languages.

use readinglog_native::lang::Lang;

pub struct Words {
    /// The heading over each week's reading, beside the Kindle's `by_month`.
    pub by_week: &'static str,
    /// `mode_timeline`, `mode_book`: the chips naming the two [`super::Mode`]s.
    pub mode_timeline: &'static str,
    pub mode_book: &'static str,
    pub choose_backup: &'static str,
    pub drop_hint: &'static str,
    pub where_backups: &'static str,
    /// `syncing_in`, `syncing_out`: the line `kindle_card` states as a sync takes the
    /// record and gives the notes; `synced` as of `{t}`, `not_synced` for `{why}`
    /// (`in_use`, `unplugged`); `try_again`, its button.
    pub syncing_in: &'static str,
    pub syncing_out: &'static str,
    pub synced: &'static str,
    pub not_synced: &'static str,
    pub in_use: &'static str,
    pub unplugged: &'static str,
    pub try_again: &'static str,
    pub show_folder: &'static str,
    pub change_folder: &'static str,
    pub added: &'static str,
    pub nothing_new: &'static str,
    /// What a book from a backup naming no Kindle is said to be from.
    pub from_backup: &'static str,
    /// The button on the Kindle's `reset_row` that asks [`Words::reset_ask`].
    pub remove_everything: &'static str,
    /// What Reset asks, `reset_note` under it and `reset_do` its answer.
    /// `{what}` is the sittings and books, `{folder}` the record's folder,
    /// `{size}` what it all takes.
    pub reset_ask: &'static str,
    pub reset_note: &'static str,
    pub reset_do: &'static str,
    pub reset_done: &'static str,
    /// The button on each backup, asking the Kindle's `delete_ask` over
    /// `delete_note`: `{file}` the backup's name, `{size}` its weight.
    pub delete: &'static str,
    pub delete_note: &'static str,
    /// The button under the backups, asking `delete_all_ask` over
    /// `delete_all_note`: `{n}` the backups, `{size}` their weight.
    pub delete_all: &'static str,
    pub delete_all_ask: &'static str,
    pub delete_all_note: &'static str,
    pub delete_all_do: &'static str,
    /// The button on each highlight opening its words, and the editor's `save`
    /// and `revert` beside the Kindle's `cancel`; `revert_tip` is `revert`'s tooltip.
    pub edit: &'static str,
    pub save: &'static str,
    pub revert: &'static str,
    pub revert_tip: &'static str,
    /// The field a note is written in, and the button on a highlight adding one.
    pub write_note: &'static str,
    pub add_note: &'static str,
    /// What deleting a note asks, `delete_note_said` under it.
    pub delete_note_ask: &'static str,
    pub delete_note_said: &'static str,
    /// `title_field` … `tag_field`: the fields the book page and the bulk editor name;
    /// `add_type`, the field adding a type to a book, and `add`, the bulk editor's Add.
    pub title_field: &'static str,
    pub authors_field: &'static str,
    pub publisher_field: &'static str,
    pub language_field: &'static str,
    pub tags_field: &'static str,
    pub type_field: &'static str,
    pub tag_field: &'static str,
    pub add_type: &'static str,
    pub add: &'static str,
    /// `book_says`: under an edited title or author, the book's own words `{s}`.
    pub book_says: &'static str,
    /// `in_use_head`, `others_head`: the language list's heads, over the languages set and the rest.
    pub in_use_head: &'static str,
    pub others_head: &'static str,
    /// `not_set`: a field no book's rows set, wherever it is named or charted.
    pub not_set: &'static str,
    /// `author_chip`: the filter chip's name for an author; `remove_tip`, the tooltip taking a tag
    /// off; `rename_type_tip`, a type's on the book page.
    pub author_chip: &'static str,
    pub remove_tip: &'static str,
    pub rename_type_tip: &'static str,
    /// `rename`, `rename_ask` (`{v}` the value, `{d}` the books), `rename_do`:
    /// Rename… on a filter chip, its field's question and its button.
    pub rename: &'static str,
    pub rename_ask: &'static str,
    pub rename_do: &'static str,
    /// `chosen` (`{n}` of `{d}` books picked), `edit_many`, `unpick`: the selection bar.
    pub chosen: &'static str,
    pub edit_many: &'static str,
    pub unpick: &'static str,
    /// `edit_books` … `apply_to`: the bulk editor's head, note, a field's "leave as is"
    /// (`{d}` values among the books, or none set), each field's way back (`each_own`,
    /// `empty`), a tag on `{n}` of `{d}` books, and Apply.
    pub edit_books: &'static str,
    pub leave_note: &'static str,
    pub leave: &'static str,
    pub leave_values: &'static str,
    pub leave_none: &'static str,
    pub each_own: &'static str,
    pub empty: &'static str,
    pub of_some: &'static str,
    pub apply_to: &'static str,
    /// `changed`, `undo`: what an edit of several books says, and the button taking it back.
    pub changed: &'static str,
    pub undo: &'static str,
    /// `look_lang`, `set_lang`, `surname_first`, `turn_them`: the suggestions, `{d}` books
    /// whose characters say `{lang}` (`{titles}`), `{d}` authors surname first (`{list}`).
    pub look_lang: &'static str,
    pub set_lang: &'static str,
    pub surname_first: &'static str,
    pub turn_them: &'static str,
    /// `authors_head` … `languages_head`: the charts' heads; `counts_each`, a type's note (`{t}` the time read).
    pub authors_head: &'static str,
    pub publishers_head: &'static str,
    pub languages_head: &'static str,
    pub counts_each: &'static str,
    /// `show_all`, `show_top`: the button under a ranked chart opening its `{d}` bars, and closing them to the first `{d}`.
    pub show_all: &'static str,
    pub show_top: &'static str,
    /// `search_books`: the Books search's hint, naming publishers and tags too.
    pub search_books: &'static str,
}

